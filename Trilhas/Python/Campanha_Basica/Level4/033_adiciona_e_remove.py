#
# DICA
# ----
# - .append(x)  -> adiciona no fim
# - .insert(i,x)-> insere na posicao i
# - .remove(x)  -> remove a PRIMEIRA ocorrencia do valor x
# - .pop()      -> remove e RETORNA o ultimo item
#
# VALIDACAO
# ---------
# Depois das operacoes, a lista final e ['bruno', 'carla'].
