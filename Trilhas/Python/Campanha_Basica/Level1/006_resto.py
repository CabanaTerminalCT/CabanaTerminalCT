# =============================================================================
# 006 - Resto da divisao
# Nivel: 2 estrelas
# Conceitos: % (modulo), // (divisao inteira)
# =============================================================================
#
# HISTORIA
# --------
# Na CabanaTerminal a galera organiza mutiroes em grupos iguais. Sobra sempre
# alguem? Quem fica de fora? Pra isso existem o resto (%) e a divisao inteira
# (//).
#
# TAREFA
# ------
# 1. Peca dois numeros inteiros (a e b)
# 2. Mostre o resultado da divisao inteira a // b
# 3. Mostre o resto da divisao a % b
#
# Exemplo de execucao:
#
#   $ python3 006_resto.py
#   Dividendo: 17
#   Divisor: 5
#   Divisao inteira: 3
#   Resto: 2
#
# REQUISITOS
# ----------
# [ ] Converte as entradas com int()
# [ ] Usa // e %
# [ ] Mostra os dois resultados separadamente
#
# DICA
# ----
# - // devolve so a parte inteira: 17 // 5 -> 3
# - %  devolve o que sobrou:       17 % 5  -> 2
#
# Teste tambem com 10 // 2 e 10 % 2 - o resto zero e a base pra descobrir se
# um numero e par.
#
# VALIDACAO
# ---------
# 17 e 5 -> divisao inteira 3, resto 2. 10 e 2 -> 5 e 0.
