#
# HISTORIA
# --------
# A saudacao da CabanaTerminal fica melhor se chamar o membro pelo nome. Uma
# funcao com parametros recebe dados de fora e trabalha com eles.
#
# TAREFA
# ------
# 1. Defina saudacao(nome) que imprime "Salve, <nome>!"
# 2. Chame com tres nomes diferentes
# 3. Defina dobro(n) que retorna n * 2
# 4. Imprima o dobro de alguns numeros
#
# Exemplo de execucao:
#
#   $ python3 052_recebe_parametros.py
#   Salve, ana!
#   Salve, bruno!
#   Salve, carla!
#   Dobro de 5: 10
#   Dobro de 12: 24
#
# REQUISITOS
# ----------
# [ ] Funcao com pelo menos um parametro
# [ ] Chama passando argumentos diferentes
# [ ] Funcao que retorna valor
#
# DICA
# ----
# O nome dentro do def e o parametro; o valor que voce passa na chamada e o
# argumento. Eles se ligam na hora da execucao.
#
# VALIDACAO
# ---------
# Cada chamada usa o nome passado; dobro(5) -> 10 e dobro(12) -> 24.
