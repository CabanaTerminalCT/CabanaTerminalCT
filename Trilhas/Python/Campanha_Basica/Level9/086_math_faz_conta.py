# HISTORIA
# --------
# A trilha de CTF da CabanaTerminal tem desafios de cripto que precisam de
# matematica de verdade: potencias, raiz, log, piso e teto. O modulo math
# entrega tudo pronto.
#
# TAREFA
# ------
# 1. Calcule a raiz quadrada de um numero
# 2. Calcule uma potencia com math.pow
# 3. Use math.floor e math.ceil em um numero decimal
# 4. Calcule o logaritmo de 100 na base 10 (math.log10)
#
# Exemplo de execucao:
#
#   $ python3 086_math_faz_conta.py
#   Raiz de 49: 7.0
#   2^8: 256.0
#   floor(3.7): 3
#   ceil(3.2): 4
#   log10(100): 2.0
#
# REQUISITOS
# ----------
# [ ] Importa math
# [ ] Usa math.sqrt, math.pow, math.floor, math.ceil
# [ ] Usa math.log10
#
# DICA
# ----
# floor arredonda pra baixo, ceil pra cima, mesmo com .5 no meio. math.pow
# devolve float, diferente do operador **.
#
# VALIDACAO
# ---------
# sqrt(49) -> 7.0; pow(2,8) -> 256.0; floor(3.7) -> 3; ceil(3.2) -> 4;
# log10(100) -> 2.0.
