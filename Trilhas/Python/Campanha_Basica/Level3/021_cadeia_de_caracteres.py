# HISTORIA
# --------
# No terminal da CabanaTerminal todo texto e uma cadeia de caracteres
# (string). Cada letra tem uma posicao, comecando do zero. Saber medir e
# acessar posicoes e o primeiro passo pra manipular texto.
#
# TAREFA
# ------
# 1. Peca uma palavra ao usuario
# 2. Mostre quantos caracteres ela tem (len)
# 3. Mostre o primeiro caractere
# 4. Mostre o ultimo caractere (usando indice negativo)
#
# Exemplo de execucao:
#
#   $ python3 021_cadeia_de_caracteres.py
#   Palavra: cabana
#   Tamanho: 6
#   Primeira letra: c
#   Ultima letra: a
#
# REQUISITOS
# ----------
# [ ] Usa len()
# [ ] Acessa o indice 0
# [ ] Acessa o ultimo com indice -1
#
# DICA
# ----
# "cabana"[0] -> "c" e "cabana"[-1] -> "a". O indice comeca em 0, entao o
# ultimo caractere esta em len - 1 (ou -1, mais facil).
#
# VALIDACAO
# ---------
# "cabana" -> 6, "c", "a". "x" -> 1, "x", "x".
